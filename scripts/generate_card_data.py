#!/usr/bin/env python3
"""Generate compiled card tables and a neutral versioned export from targets.json.

Standard library only; --check compares bytes and never writes. Paths are bound
to this script's checkout, independent of cwd. No RL or image inputs.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/bga-second-edition/targets.json"
CPP = ROOT / "include/card_data.generated.h"
EXPORT = ROOT / "data/generated/cards-v1.json"
RESOURCES = ("wood", "ore", "clay", "stone", "loom", "glass", "papyrus", "coins")
COLORS = ("brown", "grey", "blue", "yellow", "red", "green", "purple")
# Package 5-II implements these separately, with dedicated runtime regressions.
DEFERRED = {76: "ludus_count_effect", 78: "decorators_wonder_complete"}


def literal(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, (tuple, list)):
        return "{" + ", ".join(map(literal, value)) + "}"
    return str(value)


def artifacts():
    source = SOURCE.read_bytes()
    target = json.loads(source)
    if target["format_version"] != 1:
        raise ValueError("Unsupported target schema")
    rows = target["cards"]
    by_key = {c["key"]: c for c in rows}
    if len(rows) != 80 or len(by_key) != 80:
        raise ValueError("Expected 80 distinct card-age rows")
    digest = hashlib.sha256(source).hexdigest()
    cpp = ["// Generated by scripts/generate_card_data.py; do not edit.",
           "// Source: data/bga-second-edition/targets.json, SHA-256 " + digest,
           "#ifndef CARD_DATA_GENERATED_H", "#define CARD_DATA_GENERATED_H",
           '#include "card_data.h"', "namespace DMAG {",
           'inline constexpr const char* GENERATED_CARD_DATA_SHA256 = "' + digest + '";',
           "inline const std::vector<CardDefinition> GENERATED_CARD_DEFINITIONS = {"]
    allowed = {"production", "choice", "tradable", "vp", "coins", "shields", "science",
               "discount", "vp_per", "coins_per", "count", "target", "includes_self", "condition"}
    for c in rows:
        e = c["effects"]
        if set(e) - allowed or set(c["cost"]) - set(RESOURCES):
            raise ValueError("Unmapped card fields: " + c["key"])
        effects = [[e.get("production", {}).get(r, 0) for r in RESOURCES[:7]],
                   [RESOURCES.index(r) for r in e.get("choice", [])], e.get("tradable", False),
                   *[e.get(k, 0) for k in ("vp", "coins", "shields")],
                   e.get("science", ""), e.get("discount", ""),
                   e.get("vp_per", 0), e.get("coins_per", 0),
                   e.get("count", ""), e.get("target", ""),
                   e.get("includes_self", False), e.get("condition", ""),
                   c["engine_id"] not in DEFERRED]
        fields = [c["key"], c["name"], c["engine_id"], COLORS.index(c["color"]), c["age"],
                  [c["cost"].get(r, 0) for r in RESOURCES],
                  [c["counts_by_players"][str(n)] for n in range(3, 8)],
                  [(by_key[k]["engine_id"], by_key[k]["age"]) for k in c["chain_from"]], effects]
        cpp.append("    " + literal(fields) + ",")
    cpp += ["};", "}", "#endif", ""]
    export = dict(format_version=1, ruleset=target["ruleset"],
                  second_edition_implemented=False,
                  source=dict(path="data/bga-second-edition/targets.json", sha256=digest, format_version=1),
                  runtime_scope=dict(players=3, wonders="legacy", card_tables=True,
                                     deferred_effects={str(k): v for k, v in DEFERRED.items()}),
                  deck_policy=target["deck_policy"], retired_cards=target["retired_cards"], cards=rows)
    return {CPP: "\n".join(cpp).encode(),
            EXPORT: (json.dumps(export, ensure_ascii=False, indent=2) + "\n").encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, data in artifacts().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit("Stale generated artifact: " + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print("Card tables: 80 rows, format 1; " + ("checked without writes" if args.check else "generated"))


if __name__ == "__main__":
    main()
